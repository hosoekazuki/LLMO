@dataclass(frozen=True)
class StorageConfig:
    """データの保存先。"""

    # 評価結果を貯める SQLite ファイル
    db_path: str = "data/llmo.db"

    # LLMO 最適化の指示（記事の書き方の条件）を置くファイル。
    # 画面から編集した内容をここに保存し、既定の文面を上書きする。
    # ファイルが無ければ既定の文面を使う。
    rules_path: str = "data/llmo_rules.md"

    # 取得した疑似ウェブの本文を置くディレクトリ。
    # README の「前後で同じ検索結果を用いる」を守るため、
    # 一度取得したら固定して再取得しない。
    corpus_dir: str = "data/corpus"


# 他のモジュールはこのインスタンスを import して使う。
MODELS = ModelConfig()
EVAL = EvalConfig()
EMBEDDING = EmbeddingConfig()
STORAGE = StorageConfig()
