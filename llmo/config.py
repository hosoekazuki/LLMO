@dataclass(frozen=True)
class EmbeddingConfig:
    """埋め込みモデルの動かし方。モデル名は ModelConfig.embedding にある。"""

    # 一度に変換するテキストの数。
    #
    # 既定の 32 ではなく 16 にしているのは、WSL に割り当てられている
    # メモリが 4GB しかないため。バッチを大きくすると、
    # 長いチャンクが固まったときに確保が失敗する。
    batch_size: int = 16

    # 検索対象の文書に付ける接頭辞。
    #
    # ruri v3 は接頭辞を前提に学習されており、付けないと精度が落ちる。
    # 文書とクエリで別の接頭辞を使うことで、
    # 「質問文」と「それに答える説明文」が近づく空間に写される。
    # 文字列はモデルカードの記載に合わせている。
    # ruri は版によって接頭辞が違う（初代は「文章: 」「クエリ: 」）ので、
    # モデルを差し替えるときは必ずモデルカードを確認すること。
    #
    # 接頭辞は変換の直前にだけ付ける。
    # 保存するチャンク本文には含めない。本文は画面表示と引用の判定に使うため。
    document_prefix: str = "検索文書: "

    # 検索クエリに付ける接頭辞。
    query_prefix: str = "検索クエリ: "


