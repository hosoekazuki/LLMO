"""設定値と API キーを 1 か所にまとめるモジュール。

評価条件の数値（取得件数 K、生成回数 n など）をコード中に直接書くと、
「どの条件で測った結果なのか」が後から分からなくなる。
実験条件はすべてここに集約し、他のモジュールはここから読む。
"""

import os
from dataclasses import dataclass

from dotenv import load_dotenv

# プロジェクト直下の .env を読み込む。
# .env は .gitignore 済みなので、API キーがリポジトリに入ることはない。
load_dotenv()


# ---------------------------------------------------------------------------
# API キー
# ---------------------------------------------------------------------------

def _require_env(name: str) -> str:
    """環境変数を読む。未設定なら、その場で分かりやすく落とす。

    キーが無いまま処理を進めると、API 呼び出しの深いところで
    認証エラーになって原因が分かりにくい。起動時点で弾いてしまう。
    """
    value = os.getenv(name)
    if not value:
        raise RuntimeError(
            f"環境変数 {name} が設定されていません。"
            f"プロジェクト直下の .env に {name}=... を書いてください。"
        )
    return value


def get_gemini_api_key() -> str:
    """Gemini の API キーを返す。"""
    return _require_env("GEMINI_API_KEY")


def get_tavily_api_key() -> str:
    """Tavily の API キーを返す。"""
    return _require_env("TAVILY_API_KEY")


# ---------------------------------------------------------------------------
# 使用するモデル
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class ModelConfig:
    """使う Gemini モデルの名前。

    生成用と埋め込み用で別のモデルを使う。
    frozen=True にしているのは、実行中に誰かが書き換えて
    条件が変わってしまうのを防ぐため（実験の再現性のため）。
    """

    # 記事の書き直し、クエリ生成、回答生成に使うモデル。
    #
    # lite を使うのは、無料枠の日次上限（RPD）の都合。
    # このモデルは 1 評価あたり
    #   クエリ生成 1 + タイトル案 1 + 記事 1 + 回答生成（クエリ数 × 条件数 × 試行回数）
    # を呼ぶ。クエリ 15 本ならパターン A で 18 回、パターン B で 33 回になる。
    # 非 lite の Flash 系はどの世代も RPD が 20 しかなく、
    # パターン B は 1 回も完走できない。RPD 500 を持つのは lite 系だけである。
    #
    # 判定側と分けているのは、同じモデルに自分の書いた文章を採点させないため。
    # 別のモデルにすると毎分の上限（RPM 15）も別枠になる。
    # 同じモデルだと 1 評価の呼び出しが 1 つの枠に集中する。
    generation: str = "gemini-3.1-flash-lite"

    # Answer Grounding や Top Recommendation の判定に使うモデル。
    #
    # 生成と評価を同じモデルにすると自分の文章を甘く評価する偏りが入るため、
    # 意図的に別のモデルにしている。
    # 判定は回答を読んで判断する作業なので、生成側より能力の高いものを充てる。
    #
    # 判定の呼び出しは 1 評価あたり「回答の本数 × 2」（推奨・根拠）で、
    # クエリ 15 本・試行 1 回ならパターン A で最大 30 回、パターン B で最大 60 回。
    # 生成側より多いため、RPD 20 のモデルでは 1 回も完走できない。ここも lite にする。
    # 生成側より新しい世代を充てて、判定の能力が生成を下回らないようにする。
    judge: str = "gemini-3.5-flash-lite"

    # 検索クエリを「読者の状況・課題」に言い換えるモデル。
    #
    # 記事生成にクエリ文字列をそのまま渡すと、見出しに転記されてしまう。
    # 埋め込みは文字列の一致に強く反応するため、それだけで検索上位に入り、
    # 評価が自己成就する。間に言い換えを挟んで転記の経路を断つ。
    #
    # 生成と同じモデルでも構わないが、別に持たせているのは、
    # 言い換えの質が評価全体の公平性を左右するためである。
    #
    # ここだけ非 lite を使う。呼び出しが 1 評価につき 1 回だけなので、
    # RPD 20 でも 1 日 20 評価まで回せて上限に当たらない。
    # 回数を要求しないぶん、最上位のモデルを充てられる。
    transform: str = "gemini-3.5-flash-lite"

    # テキストをベクトルに変換するモデル。
    #
    # ここだけ API ではなく、手元で動くモデルを使う。
    # 疑似ウェブを作り直すたびにコーパス全体を埋め込むため、
    # API では無料枠の上限に当たって評価が完走しない。
    # 手元で動かせば回数の制限が無くなり、同じ入力に対して常に同じベクトルが出る。
    # API のモデルは更新されるとベクトルが変わるので、再現性の面でも都合がよい。
    #
    # cl-nagoya/ruri-v3-30m は日本語に特化した約 37M パラメータのモデルで、
    # 256 次元。CPU で動き、メモリ 4GB の環境でも収まる。
    #
    # このモデル名は埋め込みキャッシュの指紋（embed.py）と
    # 実験条件のハッシュ（db.condition_key）の両方に入っている。
    # 変更すると既存のベクトルは使われずに計算し直しになり、
    # 過去の評価結果とも比較できなくなる。
    embedding: str = "cl-nagoya/ruri-v3-30m"


# ---------------------------------------------------------------------------
# 評価条件
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class EvalConfig:
    """疑似ウェブでの評価条件。README の「疑似ウェブによる評価環境」に対応する。"""

    # 1 つのユーザー入力から作るクエリの本数。
    # Mention Rate などは「複数クエリのうち何割で出現したか」なので、
    # ここが評価の分母になる。
    #
    # 20 本にしているのは、割合の刻みを細かくするため。
    # 10 本だと 1 本ぶんが 0.10 になり、検索ヒット率が 0.20 なのか 0.10 なのかを
    # 判断したいときに、たった 1 本拾われたかどうかで結論が変わってしまう。
    #
    # 検索ヒット率のばらつきを減らす手段はこれしかない。
    # 検索は試行のループの外で 1 回だけ実行され（pipeline._evaluate_conditions）、
    # 埋め込みは手元のモデルで決定的なので、num_runs を増やしても順位は動かない。
    # num_runs が効くのは、回答生成に依存する指標
    #（言及率・引用率・引用シェア・最推奨率・根拠寄与率）だけである。
    num_queries: int = 20

    # ユーザーに提示するタイトル案の数。
    # 少なすぎると似た案ばかりで選択肢が尽き、
    # 多すぎると読み比べる負担が勝つ。
    num_title_candidates: int = 8

    # 1 クエリあたり Tavily から取得するページ数。疑似ウェブの材料の量。
    tavily_results_per_query: int = 5

    # 疑似ウェブに入れる文書の最低文字数。これ未満は捨てる。
    # 本文の取得に失敗したページが、数十字のタイトル程度の中身で返ってくることがある。
    # そのまま残すと、中身が無いのに検索候補の枠を 1 つ潰してしまう。
    # 実際の記事は数千〜数万字あるため、この値が競争のハードルになることはない。
    min_content_chars: int = 500

    # ベクトル検索で取り出す上位件数。すべての条件で共通。
    #
    # 条件によって K を変えないのは、README の「未公開記事は必ず 1 本だけ差し込む」
    # という前提があるため。どの条件でもベースコーパスと差し込む本数が同じなので、
    # 検索の枠を奪い合う条件が揃っており、K をずらす必要がない。
    top_k: int = 5

    # 回答生成のとき、1 出典あたり LLM に渡す本文の最大文字数。
    #
    # 検索で選ばれた記事は、当たったチャンクだけでなく本文をそのまま渡す。
    # 実際の生成 AI もページの関連箇所だけを抜き出して読むのではなく、
    # 取得したページの本文をコンテキストに入れて回答を書くため。
    # チャンクだけを渡すと、記事のどこを読ませるかをこちら側が先回りして
    # 決めてしまうことになり、引用先の選択が実態から離れる。
    #
    # 上限を設けるのは、記事の長さが交絡しないようにするため。
    # 数万字の未公開記事と数千字の他社記事をそのまま並べると、
    # 自社記事だけがコンテキストを占有して有利になる。
    # ただし上限で切り揃えても、これより短い記事は短いままなので、
    # 分量の差が完全に消えるわけではない。
    max_source_chars: int = 8000

    # 同じ条件で回答を生成する回数。LLM の出力は毎回変わるため、
    # 1 回だけだと差が偶然に埋もれる。平均を取って比較する。
    # まずは 1 でパイプラインを通し、動いたら 3 に上げる。
    num_runs: int = 1

    # 見出しと検索クエリの文字列一致率の上限。
    #
    # これを超える見出しがあれば、クエリの転記が起きたとみなして警告する。
    # 0.0〜1.0 で、1.0 は完全一致。
    # 日本語は助詞や語尾が共通しやすく、無関係な文でも 0.3〜0.4 は出るため、
    # 「言い回しを変えただけ」を捕まえられる程度に高めの値から始める。
    leakage_threshold: float = 0.6

    # 転記を検出したときに記事を作り直すか。
    #
    # 既定は False。検出と記録を必須とし、作り直しは任意機能とする。
    # 意味的な類似による有利は原理的に残るので、作り直しを繰り返しても
    # 完全に公平にはならず、API の呼び出しだけが増えるためである。
    regenerate_on_leakage: bool = False

    # 作り直す場合の上限回数。
    # 際限なく繰り返すと、無料枠を使い切ったうえで評価が完走しない。
    max_regenerations: int = 1

    # 文書を分割するチャンクの大きさ（文字数の目安）。
    # 記事を丸ごと 1 ベクトルにすると「どの主張が効いたか」が見えないので、
    # 段落くらいの粒度に割る。
    chunk_size: int = 500

    # チャンク同士を重ねる文字数。境界で文が切れて意味が壊れるのを防ぐ。
    chunk_overlap: int = 100


# ---------------------------------------------------------------------------
# 埋め込みの設定
