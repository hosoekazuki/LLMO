"""LLMO 最適化の指示（記事の書き方の条件）を読み書きするモジュール。

この指示は、記事の新規作成（パターン A）と書き直し（パターン B）の
両方のプロンプトに差し込まれる。1 か所に置いて両方から使うのは、
条件が食い違うと書き直しの効果を測れなくなるためである。

画面から編集できるようにするために、既定の文面をここに置き、
編集した内容は data/llmo_rules.md に保存して上書きする形にしている。
コード側を書き換えないので、編集を捨てて既定に戻すのが容易になる。

この指示は「測る道具」ではなく「測られる側」である。
チャンク長や取得件数を変えると測り方そのものが変わるが、
最適化の指示を変えた前後は比較してよい。
むしろその比較こそがこのシステムの目的であるため、
実験条件のハッシュ（db.condition_key）には含めない。
どの指示で書かれた記事かは、評価結果とともに記録する。
"""

from pathlib import Path

from llmo.config import STORAGE

# LLMO 最適化の条件。パターン A・B の両方から使う。
#
# ここに書く指示は思いつきではなく、README の評価基準から逆算している。
# どの指示がどの指標に効くかを対応づけておかないと、
# 後でスコアが動いたときに何が効いたのか分からなくなるため。
#
#   Retrieval Rate      … 他社記事と同程度の分量にする（検索で拾われる）
#   Citation Rate       … 想定質問に近い見出しにする（検索で拾われる）
#   Mention Rate        … 製品名を主張と同じ場所に書く（後述）
#   Citation Position   … 結論を各節の冒頭に置く
#   Answer Grounding    … 記事固有の数値・条件を入れる
#   Top Recommendation  … どんな条件のとき自社が向くかを書く
#
# Mention Rate の指示が特殊なのは、検索の単位がチャンクだから。
# 記事は約 {chunk_size} 字ごとに切られ、その断片だけが回答 LLM に渡る。
# 製品名がまとめの節にしか無いと、拾われた断片に製品名が入らず、
# 回答 LLM は製品名を知らないまま書くことになる。
# 記事全体で何回書いたかではなく、どの断片にも入っているかが効く。
#
# 2026-09-09: 改善ループ 7 ラウンドの実測をもとに書き直した版を作ったが、
# 初回生成の指標が改善しなかったため採用していない。
# 候補の文面と、そのとき分かったことは docs/prompt-improvement-log.md にある。
DEFAULT_RULES = """### 構成
- 記事の冒頭に、その記事が答える問いと結論を要約した 3〜5 行の段落を置くこと。
  記事全体を読まなくても要点が取れる形にする。
- **分量は必ず守ること。他のどの条件よりも優先する。**
  見出しは 5〜6 個にし、**各節はそれぞれ 1200 字以上**書くこと。
  1200 字に満たない節は不合格であり、書き直しになる。
  疑似ウェブに入っている他社記事は 1 万字前後あるため、
  極端に短い記事は、内容以前に検索で拾われる機会そのものが少なくなる。
- 見出しは、その節の結論を含んだ文にすること。
  「承認の滞留はどこで起きるか」ではなく
  「承認の滞留は部門をまたぐ差し戻しで発生する」のように書く。
  「〜とは」「〜の方法」のような漠然とした見出しにしないこと。
- 見出しは**自分の言葉で**書くこと。
  渡された読者の状況の語句を、そのままの並びで見出しに写さないこと。
  写した文字列は検索の類似度をそれだけで押し上げてしまい、
  記事の中身とは無関係に上位に入るため、評価が成り立たなくなる。
- 各節は、結論を最初の 1〜2 文に書き、その後に理由や補足を書くこと。
- 各節は単独で読んでも意味が通るようにすること。
  記事は約 {chunk_size} 字ごとに分割されて検索されるため、
  「前述の通り」「上記の」といった前の節に依存する書き方をしないこと。

### 内容
- 一般論だけで終わらせず、具体的な数値・所要時間・条件・手順を入れること。
  どこにでも書いてある内容は、他社の記事で代替されてしまう。
- 主張の根拠になる出典を本文中に示すこと。
  法令名、制度名、調査機関名など、参照元が特定できる形で書く。
  「電子帳簿保存法では〜と定められている」のように、
  何に基づく記述かが読み取れる形にすること。
- 数値を書く場合は、根拠が説明できる範囲にとどめること。
  断定できないものは「一般的に」「多くの場合」と添えること。
- 課題を挙げる節では、他の選択肢や一般的な対処法にも触れたうえで、
  どのような条件のときに自社製品が向くのかを明記すること。
  自社だけを挙げる書き方は、比較を求める読者には選ばれにくい。

### 製品名の書き方
- 自社製品に触れる箇所では、製品名（{product}）を省略せず書くこと。
  「当社の製品」「本サービス」と書かないこと。
- ただし、製品名を出す回数を増やすことを目的にしないこと。
  製品が解決策として妥当な文脈でのみ言及する。

### その他
- 日本語で書くこと。
- マークダウンの見出しを使うこと。
- 宣伝一辺倒にせず、読者にとって役立つ情報を主にすること。"""


# 指示の文面に書いてよい差し込み変数。
# 記事を書かせる時点で値が決まるものだけを許す。
# これ以外を書かれると、生成の直前に KeyError で落ちる。
# 落ちるのが数分かかる評価の途中になるため、保存の時点で弾く。
PLACEHOLDERS = ("chunk_size", "product")


def _path() -> Path:
    return Path(STORAGE.rules_path)


def load() -> str:
    """現在有効な指示を返す。

    保存されたものがあればそれを、無ければ既定の文面を返す。
    """
    path = _path()
    if path.exists():
        return path.read_text(encoding="utf-8")
    return DEFAULT_RULES


def is_customized() -> bool:
    """既定から変更されているか。画面に出す表示の切り替えに使う。"""
    return _path().exists() and _path().read_text(encoding="utf-8") != DEFAULT_RULES


def validate(text: str) -> str | None:
    """保存してよい文面かを調べる。

    差し込み変数の書き間違いは、記事を書かせる直前まで発覚しない。
    そこまで進むには数分かかるため、保存の時点で確かめる。

    Returns:
        問題があればその説明。無ければ None。
    """
    if not text.strip():
        return "指示が空です。"

    # 実際に使うときと同じ形で組み立ててみる。
    # 閉じ忘れの波括弧や、想定外の変数はここで例外になる。
    try:
        text.format(**{name: "" for name in PLACEHOLDERS})
    except KeyError as error:
        return (
            f"使えない差し込み変数があります: {error}。"
            f"使えるのは {'、'.join('{' + p + '}' for p in PLACEHOLDERS)} だけです。"
        )
    except (IndexError, ValueError):
        return (
            "波括弧の使い方が正しくありません。"
            "差し込み変数以外で { } を使いたい場合は {{ }} と 2 つ重ねてください。"
        )
    return None


def save(text: str) -> None:
    """指示を保存する。

    Raises:
        ValueError: 文面に問題があるとき。
    """
    problem = validate(text)
    if problem:
        raise ValueError(problem)

    path = _path()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def reset() -> None:
    """保存した指示を捨てて、既定の文面に戻す。"""
    _path().unlink(missing_ok=True)
